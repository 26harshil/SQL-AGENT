from typing import Literal, Optional, List, Annotated, Any
from operator import add
from pydantic import BaseModel, Field


class AgentSchema(BaseModel):
    messages: Annotated[List[Any], add] = Field(default_factory=list, description="List of messages processed by the agent")
    user_question: str = Field(default="", description="The original question asked by the user")
    curated_ques: str = Field(default="", description="Curated user question")
    prompt_query_context: str = Field(default="", description="A detailed prompt with SQL DB context")
    generated_sql_query: str = Field(default="", description="The SQL query generated by the agent")
    sql_guard_passed: bool = Field(default=False, description="Whether deterministic SQL AST guard passed")
    sql_guard_reason: str = Field(default="", description="Reason from deterministic SQL AST guard")
    normalized_sql: Optional[str] = Field(default=None, description="Dialect-normalized SQL query")
    is_safe: Literal["Yes", "No"] = Field(default="No", description="LLM judge safety verdict")
    comments: str = Field(default="", description="LLM judge safety comments")
    sql_query_execution_result: str = Field(default="", description="Result of executing SQL query")
    final_answer: str = Field(default="", description="Final formatted answer to user")


class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(..., description="Indicates whether the generated SQL query is safe to execute or not")
    comments: str = Field(..., description="Additional comments or feedback from the judge regarding the SQL query")


class ETLAgentSchema(BaseModel):
    messages: Annotated[List[Any], add] = Field(default_factory=list, description="List of messages to be processed by the ETL agent")


class RouterSchema(BaseModel):
    answer: Literal["sql", "etl"] = Field(..., description="Indicates whether the user's question is related to SQL or ETL operations")
    comments: str = Field(..., description="Additional comments or feedback regarding the classification of the user's question")


class DataAgentSchema(BaseModel):
    messages: Annotated[List[Any], add] = Field(default_factory=list, description="List of messages to be processed by the Data agent")
    route_response: str = Field(default="", description="The response from the router indicating whether to route to SQL or ETL operations")
